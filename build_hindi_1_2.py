def format_q(q):
    def esc(s):
        return s.replace('\\', '\\\\').replace('"', '\\"')
    
    return f"""        Question(
            id = {q['id']}L,
            questionId = "{q['qid']}",
            subjectId = "SUB_HINDI",
            topicId = "{q['topic_id']}",
            chapterId = {q['ch_id']}L,
            subjectName = "सामान्य हिंदी",
            chapterName = "{esc(q['ch_name'])}",
            questionText = "{esc(q['q'])}",
            optionA = "{esc(q['a'])}",
            optionB = "{esc(q['b'])}",
            optionC = "{esc(q['c'])}",
            optionD = "{esc(q['d'])}",
            correctOption = {q['ans']},
            correctOptionLetter = "{chr(ord('A') + q['ans'])}",
            explanation = "{esc(q['exp'])}",
            difficulty = "{q['diff']}",
            language = "Hindi",
            isActive = true,
            createdDate = "2026-09-10"
        )"""

def write_part(part_num, topic_name, questions):
    content = f"""package com.example.data.db.hindi

import com.example.data.model.Question

/**
 * Hindi Question Bank - Part {part_num} (Questions {(part_num-1)*50 + 1} to {part_num*50})
 * Topic: {topic_name}
 */
object HindiQuestionsPart{part_num} {{
    fun getQuestions(): List<Question> = listOf(
""" + ",\n".join(format_q(q) for q in questions) + """
    )
}
"""
    path = f"app/src/main/java/com/example/data/db/hindi/HindiQuestionsPart{part_num}.kt"
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Written {path} with {len(questions)} questions")

